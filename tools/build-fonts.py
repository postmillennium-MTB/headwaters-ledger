#!/usr/bin/env python3
"""Regenerate the bundled-font block in index.html (ADR-001).

Run from the repo root:   python3 tools/build-fonts.py
Needs:  pip install fonttools brotli      Network: fonts.googleapis.com / fonts.gstatic.com
Idempotent: rewrites everything between the FONTS:BEGIN and FONTS:END markers.
Licenses are recorded beside each family below; confirm against fonts.google.com before shipping a new family.
"""
import base64, io, re, sys, urllib.request
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

HTML = Path(__file__).resolve().parent.parent / "index.html"
BEGIN = "/* FONTS:BEGIN — generated by tools/build-fonts.py; do not edit by hand */"
END = "/* FONTS:END */"
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/124.0 Safari/537.36")
# (family, weights, license, has weight axis)
FAMILIES = [
    ("Big Shoulders Display", [900], "SIL OFL 1.1", True),
    ("Barlow Semi Condensed", [400, 600], "SIL OFL 1.1", True),
    ("IBM Plex Mono", [500, 600], "SIL OFL 1.1", True),
    ("Special Elite", [400], "Apache 2.0", False),
    ("Cutive Mono", [400], "SIL OFL 1.1", False),
    ("Libre Caslon Text", [400, 700], "SIL OFL 1.1", True),
    ("Alfa Slab One", [400], "SIL OFL 1.1", False),
    ("Zilla Slab", [400, 700], "SIL OFL 1.1", True),
]
# Basic Latin, Latin-1, typographic punctuation, bullets, arrows the page uses.
UNICODES = ("U+0020-007E,U+00A0-00FF,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,"
            "U+2022,U+2026,U+2190-2193,U+2197,U+00B7")


def get(url, headers=None):
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers or {})).read()


def latin_woff2(family, weights, axis):
    name = family.replace(" ", "+")
    q = f"family={name}:wght@{';'.join(map(str, weights))}" if axis else f"family={name}"
    css = get(f"https://fonts.googleapis.com/css2?{q}&display=swap", {"User-Agent": UA}).decode()
    out = {}
    for sub, body in re.findall(r"/\* (\S+) \*/\s*@font-face\s*\{(.*?)\}", css, re.S):
        if sub != "latin":
            continue
        weight = int(re.search(r"font-weight:\s*(\d+)", body).group(1))
        out[weight] = get(re.search(r"url\((.*?)\)", body).group(1))
    return out


def trim(data):
    opts = subset.Options()
    opts.layout_features = ["kern", "liga"]
    opts.flavor = "woff2"
    font = TTFont(io.BytesIO(data))
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main():
    rules, total = [], 0
    header = ["  /* Bundled fonts (ADR-001). Latin subset, woff2, base64. Licenses:"]
    for family, weights, lic, axis in FAMILIES:
        files = latin_woff2(family, weights, axis)
        header.append(f"     {family} {','.join(map(str, weights))} — {lic}")
        for w in weights:
            data = trim(files[w])
            total += len(data)
            b64 = base64.b64encode(data).decode()
            rules.append(f'  @font-face{{font-family:"{family}";font-style:normal;font-weight:{w};'
                         f'font-display:swap;src:url(data:font/woff2;base64,{b64}) format("woff2")}}')
    header.append(f"     Total woff2 {total} bytes. */")
    block = BEGIN + "\n" + "\n".join(header) + "\n" + "\n".join(rules) + "\n  " + END
    src = HTML.read_text(encoding="utf-8")
    pat = re.compile(re.escape("  " + BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(src):
        sys.exit("FONTS markers not found in index.html")
    HTML.write_text(pat.sub(lambda m: "  " + block.lstrip(), src, count=1), encoding="utf-8")
    print(f"wrote {len(rules)} @font-face rules, {total} woff2 bytes, ~{total * 4 // 3} base64 bytes")


if __name__ == "__main__":
    main()
